    public String systemPromptBuild(String nickname, ToneType toneType) {
        boolean honorific = toneType == ToneType.HONORIFIC;
        String toneRule = (honorific ? HONORIFIC_TONE_RULE : INFORMAL_TONE_RULE).formatted(nickname);
        String examples = honorific ? HONORIFIC_EXAMPLES : INFORMAL_EXAMPLES;
        return SYSTEM_PROMPT.formatted(toneRule, examples);
    }

    public String userPromptBuild(String content, EmotionType emotionType) {
        return String.format(
        """
            입력: %s
            감정: %s
            """
            ,content,
            emotionType.getDisplayName()
        );
    }
